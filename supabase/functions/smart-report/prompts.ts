export function extractPrompt(lang: 'kk' | 'ru', today: string): string {
  const out = lang === 'kk' ? 'казахском' : 'русском'
  return `Ты помогаешь сотруднику МЧС Республики Казахстан (например, начальнику караула) подготовить рапорт.
Пользователь описал ситуацию своими словами. Твоя задача — только ВЫДЕЛИТЬ сведения из этого описания.

Поля:
${FACTS.map(([key, description]) => `- ${key} — ${description};`).join('\n')}

Строгие правила:
1. Бери сведения ТОЛЬКО из текста пользователя. Ничего не додумывай и не предполагай.
2. Если сведения нет — value = "" и quote = "". Не пиши «не указано», просто пустая строка.
3. quote — точный фрагмент текста пользователя, из которого взято значение.
4. Время приводи к виду ЧЧ:ММ («в 18.40», «18-40» → «18:40»).
5. value пиши на ${out} языке, кратко, без лишних слов.
6. events — хронология событий из текста по порядку, кратко, на ${out} языке.
7. title — короткое нейтральное название происшествия на ${out} языке.
8. Числа людей пиши так, как в тексте («2 человека»). «нет» пиши ТОЛЬКО если в тексте прямо сказано, что таких людей нет («погибших нет»). Если о спасённых (или других) ничего не сказано — пустая строка, не «нет».
9. Причину пожара бери только если она прямо названа в тексте.
10. Не превращай длительность во время суток: «через 9 минут» — это не «09:00». Если сказано «через N минут после …» и время того события известно — вычисли (22:00 + 9 мин = 22:09); иначе оставь поле пустым.
11. «10 часов вечера» = 22:00, «в 9 утра» = 09:00. События после вечернего вызова без уточнения «утра» относятся к тому же вечеру или ночи.
12. inferred = true, если значение не сказано прямо, а выведено из контекста. Примеры: время сообщения, когда сказано только «примерно в 9 заметили дым… позвонили пожарным»; дата из слова «сегодня» (сегодня ${today}); «приехали через несколько минут». Тогда quote — фрагмент, на котором основан вывод. Если сказано прямо — inferred = false.
13. Не путай людей: эвакуированные и пострадавшие гражданские лица (курсанты, жильцы, очевидцы) — в rescued / evacuated / injured / dead; сотрудники пожарной службы — только в staffInjuries. «Пожарные приехали» — это не эвакуация.
14. Не смешивай объект и обстановку: objectInfo — что это за объект (этажность, назначение); situation — что увидели по прибытии (горение, задымление).
15. date: если сказано «сегодня» — value = ${today}, inferred = true; «вчера» — предыдущий день, inferred = true.
16. Курсанты, учащиеся, жильцы, очевидцы, преподаватели — гражданские лица, а не личный состав пожарной службы.`
}

