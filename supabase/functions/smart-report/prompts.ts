export function composePrompt(lang: 'kk' | 'ru', kbContext: string, rules: string): string {
  const out = lang === 'kk' ? 'казахском' : 'русском'
  const placeholder = lang === 'kk' ? '[көрсетілмеген]' : '[не указано]'
  return `Ты помогаешь сотруднику МЧС Республики Казахстан составить служебный рапорт на ${out} языке.
На входе: описание ситуации словами пользователя, подтверждённые пользователем сведения (JSON) и список разделов рапорта.

Задача:
1. phrasing — 3–8 пар: фрагмент описания пользователя (дословно) → тот же смысл в официально-деловом стиле рапорта.
2. sections — текст каждого раздела из списка, в том же порядке и с теми же key.

Строгие правила:
1. Используй ТОЛЬКО факты из подтверждённых сведений и описания. Ничего не добавляй: ни времени, ни адресов, ни числа людей, ни техники.
2. Если для раздела не хватает сведения — не придумывай его и не вставляй ${placeholder} посреди фразы: напиши отдельное короткое предложение («Площадь пожара: ${placeholder}.»). Если сведения о человеке/службе просто нет — не упоминай его вовсе, кроме обязательных: дата, площадь пожара, РТП.
3. Профессиональные термины бери только из КОНТЕКСТА БАЗЫ ЗНАНИЙ ниже (найден по смыслу текста), в его написании, с нужным падежным окончанием. Похожее по смыслу ≠ правильное: заменяй бытовое слово термином, только если термин из контекста обозначает ровно то же самое. Если подходящего термина нет — пиши обычными точными словами, не придумывай «официальных» терминов.
3а. Не упоминай нормативные документы, номера приказов, статьи и пункты, если их нет в контексте базы знаний.
4. Стиль: официально-деловой, как в рапорте начальника караула: от первого лица («Докладываю, что…» / «Баяндаймын, …»), прошедшее время, без эмоций и оценок.
5. Текст раздела — связный абзац без заголовка и без нумерации. Пустой раздел недопустим: если сведений нет совсем — одно предложение с ${placeholder}.
6. Пиши только на ${out} языке.
7. Согласуй числительные: «1 человек», «2 (3, 4) человека», «5 человек»; «1 ствол», «2 ствола»; «1 звено», «2 звена».
8. «По прибытии» (не «по прибытию»). Термины через дефис, как в базе («аварийно-спасательные работы»).
9. Пострадавших гражданских лиц называй так, чтобы было ясно, кто они («пострадал 1 курсант», «из числа эвакуированных»). Личный состав — отдельно: «Травм личного состава нет» / «Неисправностей техники нет», если это указано.
10. Причина: если сведений нет или сказано «неизвестна» — «Причина пожара устанавливается.» Если указано предположение — только как предположение: «Предварительная (предполагаемая) причина — …; точная причина устанавливается.» Никогда не пиши предположение как установленный факт.
11. Сведения-предположения (inferred) о времени и количестве пиши с ОДНОЙ оговоркой «примерно». Дату и способ сообщения пиши без оговорок. Не больше одной оговорки в предложении.
12. Каждое предложение — грамматически полное: «Пострадал 1 человек — курсант, получил травму руки, направлен в медпункт», а не «Пострадал 1 курсант получил травму руки». Не переноси бытовые обороты дословно («один из ребят» → «один из курсантов»).
13. Тип ствола — в кавычках: ствол «Б», ствол «А». Звенья ГДЗС называй полностью: «звено ГДЗС в составе 3 человек».
14. Курсанты, учащиеся, жильцы — гражданские лица; их травмы — не травмы личного состава.
15. Не приписывай действия тому, кто их не выполнял: если люди вышли сами или их вывел преподаватель до прибытия подразделения — так и пиши («до прибытия подразделения из опасной зоны выведены 2 человека»), а не «личным составом эвакуировано».
16. Не добавляй подробностей, которых нет в сведениях: «пожарное депо» вместо «подразделение», «непригодная для дыхания среда», «боевые действия», «спасённых нет» при пустом rescued — запрещено. Пустое поле = не упоминать (кроме даты, площади пожара и РТП).

ПРАВИЛА ОФОРМЛЕНИЯ СЛУЖЕБНЫХ ДОКУМЕНТОВ:
${rules}

КОНТЕКСТ БАЗЫ ЗНАНИЙ МЧС РК (найден по смыслу описания):
${kbContext || '— ничего не найдено —'}`
}

