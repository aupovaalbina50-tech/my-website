-- ---- quotes table ---------------------------------------------------

create table if not exists public.quotes (
  id bigint generated always as identity primary key,
  quote_number smallint not null unique check (quote_number between 1 and 100),
  quote_text text not null,
  author text not null default 'Мәлік Ғабдуллин',
  view_count integer not null default 0,
  created_at timestamptz not null default now()
);

comment on table public.quotes is 'The 100 quotations of Malik Gabdullin shown on the /quotes pages.';

alter table public.quotes enable row level security;

create policy "Anyone can read quotes"
  on public.quotes for select
  using (true);

-- No insert/update/delete policy for the client: the table is seeded
-- below and view_count only changes via the increment_quote_view RPC.

-- ---- quote_favorites table -------------------------------------------

create table if not exists public.quote_favorites (
  user_id uuid not null references auth.users (id) on delete cascade,
  quote_id bigint not null references public.quotes (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, quote_id)
);

comment on table public.quote_favorites is 'Per-user favorited quotes, shown on /account/favorites.';

alter table public.quote_favorites enable row level security;

create policy "Users can view own favorites"
  on public.quote_favorites for select
  using (auth.uid() = user_id);

create policy "Users can add own favorites"
  on public.quote_favorites for insert
  with check (auth.uid() = user_id);

create policy "Users can remove own favorites"
  on public.quote_favorites for delete
  using (auth.uid() = user_id);

-- ---- quote_views table (per-user "recently viewed") --------------------

create table if not exists public.quote_views (
  user_id uuid not null references auth.users (id) on delete cascade,
  quote_id bigint not null references public.quotes (id) on delete cascade,
  viewed_at timestamptz not null default now(),
  primary key (user_id, quote_id)
);

comment on table public.quote_views is 'Per-user last-viewed timestamp per quote, shown on /account/viewing-history.';

alter table public.quote_views enable row level security;

create policy "Users can view own view history"
  on public.quote_views for select
  using (auth.uid() = user_id);

create policy "Users can record own view"
  on public.quote_views for insert
  with check (auth.uid() = user_id);

create policy "Users can update own view timestamp"
  on public.quote_views for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ---- global view counter (works for anonymous visitors too) ------------

create or replace function public.increment_quote_view(p_quote_number smallint)
returns void
language sql
security definer
set search_path = public
as $$
  update public.quotes set view_count = view_count + 1 where quote_number = p_quote_number;
$$;

grant execute on function public.increment_quote_view(smallint) to anon, authenticated;

-- ---- aggregate stats for the /quotes hero stat tiles --------------------

create or replace function public.get_quote_stats()
returns table (
  total_quotes bigint,
  total_favorited bigint,
  most_viewed_number smallint,
  most_viewed_count integer,
  recently_added bigint
)
language sql
security definer
set search_path = public
stable
as $$
  select
    (select count(*) from public.quotes),
    (select count(distinct quote_id) from public.quote_favorites),
    (select quote_number from public.quotes order by view_count desc, quote_number asc limit 1),
    (select view_count from public.quotes order by view_count desc, quote_number asc limit 1),
    (select count(*) from public.quotes where created_at > now() - interval '7 days');
$$;

grant execute on function public.get_quote_stats() to anon, authenticated;

