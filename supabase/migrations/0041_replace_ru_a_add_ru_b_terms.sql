create temp table old_a on commit drop as
select t.id, t.kk from public.terms t
where upper(left(trim(t.ru), 1)) = 'А'
  and not exists (select 1 from protected_terms p where lower(p.kk) = lower(t.kk) and lower(p.ru) = lower(t.ru));

-- One old card per new term with the same Kazakh text keeps its id (and user data).
create temp table keep_map on commit drop as
select distinct on (n.n) n.n, o.id
from new_a n join old_a o on lower(trim(o.kk)) = n.kk
order by n.n, o.id;
delete from keep_map k using keep_map k2 where k.id = k2.id and k.n > k2.n;

update public.terms t set kk = n.kk, ru = n.ru, en = n.en, category = n.category
from keep_map k join new_a n on n.n = k.n where t.id = k.id;

delete from public.terms t using old_a o where t.id = o.id and t.id not in (select id from keep_map);

-- A new «А» term that is already on the site (e.g. from today's lists) is not added twice.
insert into public.terms (kk, ru, en, category)
select n.kk, n.ru, n.en, n.category from new_a n
where n.n not in (select n from keep_map)
  and not exists (select 1 from public.terms t where lower(t.kk) = n.kk and lower(t.ru) = n.ru)
order by n.n;
update public.terms t set en = n.en
from new_a n
where n.n not in (select n from keep_map) and lower(t.kk) = n.kk and lower(t.ru) = n.ru;

-- «Б»: add; a card that already exists with the same kk and ru only gets the new English.
update public.terms t set en = n.en from new_b n where lower(t.kk) = n.kk and lower(t.ru) = n.ru;
insert into public.terms (kk, ru, en, category)
select n.kk, n.ru, n.en, n.category from new_b n
where not exists (select 1 from public.terms t where lower(t.kk) = n.kk and lower(t.ru) = n.ru)
order by n.n;

select (select count(*) from old_a) as old_a_replaced,
       (select count(*) from keep_map) as updated_in_place,
       (select count(*) from public.terms where upper(left(trim(ru), 1)) = 'А') as ru_a_now,
       (select count(*) from public.terms) as terms_now;

commit;
