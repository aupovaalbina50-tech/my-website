create temp table old_kk_a on commit drop as
select t.id from public.terms t
where upper(left(trim(t.kk), 1)) = 'А'
  and not exists (select 1 from today_terms d where lower(d.kk) = lower(t.kk) and lower(d.ru) = lower(t.ru));

select (select count(*) from old_kk_a) as removed,
       (select count(*) from public.term_favorites where term_id in (select id from old_kk_a)) as favorites,
       (select count(*) from public.mission_term_progress where term_id in (select id from old_kk_a)) as mission_progress;

delete from public.terms where id in (select id from old_kk_a);

select (select count(*) from public.terms where upper(left(trim(kk), 1)) = 'А') as kk_a_now,
       (select count(*) from public.terms) as terms_now;

commit;
