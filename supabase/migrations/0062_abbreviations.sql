-- =============================================================
-- «Аббревиатуры и сокращения»: a checked catalog of civil-protection
-- abbreviations, Kazakh and Russian kept apart.
--
-- One row = one abbreviation in one language with one meaning. The same
-- abbreviation with another meaning is another row (ӨСБ — «Өрт сөндіру
-- бөлімі» and «Өртті сөндіру басшысы»). Rows of the two languages that name
-- the same notion share `concept`, so a card can open its equivalent;
-- nothing is ever translated automatically.
--
-- status:
--   confirmed    — found in an official source (official_url);
--   base         — the full form is a term of the platform's base;
--   needs_review — taken from a linguistic source only, not yet confirmed.
--
-- Anyone can read published rows; only admins (profiles.role = 'admin')
-- add, change or confirm them. New rows come through
-- scripts/abbr/import.mjs (CSV/JSON -> checked SQL), not from code.
--
-- Apply: Supabase -> SQL Editor -> paste this file -> Run.
-- Running it again is safe.
-- =============================================================

create table if not exists public.abbreviations (
  id uuid primary key default gen_random_uuid(),
  lang text not null check (lang in ('kk', 'ru')),
  abbr text not null check (length(trim(abbr)) between 1 and 40),
  full_form text not null check (length(trim(full_form)) >= 2),
  -- The full form in the other language, only when confirmed.
  equivalent_full text,
  equivalent_en text,
  category text not null check (category in (
    'emergencies', 'civil_defense', 'fire_safety', 'rescue_ops', 'industrial_safety',
    'disaster_medicine', 'evacuation', 'alerting_comms', 'coordination'
  )),
  explanation text,
  example text,
  ambiguity_note text,
  concept text,
  status text not null default 'needs_review' check (status in ('confirmed', 'base', 'needs_review')),
  source_title text not null,
  source_url text,
  official_title text,
  official_url text,
  checked_at date not null default current_date,
  published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- One meaning of one abbreviation once per language.
create unique index if not exists abbreviations_unique_meaning
  on public.abbreviations (lang, abbr, lower(full_form));
create index if not exists abbreviations_lang_abbr_idx on public.abbreviations (lang, upper(abbr));
create index if not exists abbreviations_concept_idx on public.abbreviations (concept);
create index if not exists abbreviations_category_idx on public.abbreviations (category);

comment on table public.abbreviations is
  'Civil-protection abbreviations, kk and ru separately; concept links language equivalents.';

alter table public.abbreviations enable row level security;

drop policy if exists "Anyone can view published abbreviations" on public.abbreviations;
create policy "Anyone can view published abbreviations"
  on public.abbreviations for select
  using (published or exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'));

drop policy if exists "Admins can manage abbreviations" on public.abbreviations;
create policy "Admins can manage abbreviations"
  on public.abbreviations for all
  using (exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'))
  with check (exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'));

create or replace function public.abbreviations_touch()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists abbreviations_touch on public.abbreviations;
create trigger abbreviations_touch before update on public.abbreviations
  for each row execute function public.abbreviations_touch();

