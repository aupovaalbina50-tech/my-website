// Abbreviations import: a CSV or JSON file -> checked SQL for Supabase.
//
//   node scripts/abbr/import.mjs new.csv > new.sql
//   node scripts/abbr/import.mjs src/data/abbreviations.json > supabase/seed/abbreviations.sql
//
// Then: Supabase -> SQL Editor -> paste the .sql -> Run. No keys needed.
//
// Columns (CSV header or JSON keys): lang (kk|ru), abbr, full_form, category,
// source_title — required; equivalent_full, equivalent_en, explanation,
// example, ambiguity_note, concept, status (confirmed|base|needs_review,
// default needs_review), source_url, official_title, official_url,
// checked_at (YYYY-MM-DD). Errors stop the import with the row numbers;
// duplicates inside the file are reported and kept once. Re-importing is
// safe: an existing meaning (same lang, abbr, full form) is updated, never
// doubled; the same abbreviation with another full form is a new meaning.
import fs from 'node:fs'

const LANGS = ['kk', 'ru']
const CATEGORIES = ['emergencies', 'civil_defense', 'fire_safety', 'rescue_ops', 'industrial_safety', 'disaster_medicine', 'evacuation', 'alerting_comms', 'coordination']
const STATUSES = ['confirmed', 'base', 'needs_review']
const COLUMNS = ['lang', 'abbr', 'full_form', 'equivalent_full', 'equivalent_en', 'category', 'explanation', 'example', 'ambiguity_note', 'concept', 'status', 'source_title', 'source_url', 'official_title', 'official_url', 'checked_at']
const REQUIRED = ['lang', 'abbr', 'full_form', 'category', 'source_title']

/** RFC 4180 CSV: quoted fields, doubled quotes, commas or semicolons. */
function parseCsv(text) {
  const sep = (text.split('\n')[0].match(/;/g) ?? []).length > (text.split('\n')[0].match(/,/g) ?? []).length ? ';' : ','
  const rows = []
  let row = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"'
        i++
      } else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === sep) {
      row.push(field)
      field = ''
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(field)
      rows.push(row)
      row = []
      field = ''
    } else field += c
  }
  if (field || row.length) {
    row.push(field)
    rows.push(row)
  }
  const [head, ...body] = rows.filter((r) => r.some((v) => v.trim()))
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? '').trim()])))
}

export function checkRecords(records) {
  const errors = []
  const seen = new Map()
  const duplicates = []
  const out = []
  records.forEach((raw, i) => {
    const n = i + 1
    const r = Object.fromEntries(COLUMNS.map((c) => [c, typeof raw[c] === 'string' ? raw[c].trim() : (raw[c] ?? '')]))
    for (const c of REQUIRED) if (!r[c]) errors.push(`строка ${n}: нет поля ${c}`)
    if (r.lang && !LANGS.includes(r.lang)) errors.push(`строка ${n}: lang должен быть kk или ru`)
    if (r.category && !CATEGORIES.includes(r.category)) errors.push(`строка ${n}: неизвестная категория ${r.category}`)
    r.status ||= 'needs_review'
    if (!STATUSES.includes(r.status)) errors.push(`строка ${n}: неизвестный статус ${r.status}`)
    if (r.status === 'confirmed' && !r.official_url) errors.push(`строка ${n}: статус confirmed без official_url`)
    for (const c of ['source_url', 'official_url']) if (r[c] && !/^https:\/\/\S+$/.test(r[c])) errors.push(`строка ${n}: ${c} — не https-ссылка`)
    if (r.checked_at && !/^\d{4}-\d{2}-\d{2}$/.test(r.checked_at)) errors.push(`строка ${n}: checked_at в формате ГГГГ-ММ-ДД`)
    if (r.lang === 'ru' && /[әғқңөұүһі]/i.test(r.abbr + r.full_form)) errors.push(`строка ${n}: казахские буквы в русской записи`)
    const key = `${r.lang}|${r.abbr}|${r.full_form.toLowerCase()}`
    if (seen.has(key)) {
      duplicates.push(`строка ${n} повторяет строку ${seen.get(key)} (${r.abbr})`)
      return
    }
    seen.set(key, n)
    out.push(r)
  })
  return { records: out, errors, duplicates }
}

const q = (v) => (v === '' || v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

export function toSql(records) {
  const values = records.map((r) => `  (${COLUMNS.map((c) => (c === 'checked_at' && !r[c] ? 'current_date' : q(r[c]))).join(', ')})`)
  const update = COLUMNS.filter((c) => !['lang', 'abbr', 'full_form'].includes(c)).map((c) => `${c} = excluded.${c}`)
  return `-- Generated by scripts/abbr/import.mjs: ${records.length} records.
insert into public.abbreviations (${COLUMNS.join(', ')})
values
${values.join(',\n')}
on conflict (lang, abbr, lower(full_form)) do update set
  ${update.join(',\n  ')};
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const file = process.argv[2]
  if (!file) {
    console.error('Использование: node scripts/abbr/import.mjs файл.csv|файл.json > out.sql')
    process.exit(1)
  }
  const text = fs.readFileSync(file, 'utf8').replace(/^﻿/, '')
  const raw = file.endsWith('.json') ? JSON.parse(text) : parseCsv(text)
  const { records, errors, duplicates } = checkRecords(Array.isArray(raw) ? raw : raw.records ?? [])
  for (const d of duplicates) console.error(`Дубликат: ${d}`)
  if (errors.length) {
    for (const e of errors) console.error(`Ошибка: ${e}`)
    process.exit(1)
  }
  console.error(`Готово: ${records.length} записей (kk ${records.filter((r) => r.lang === 'kk').length}, ru ${records.filter((r) => r.lang === 'ru').length}).`)
  process.stdout.write(toSql(records))
}
